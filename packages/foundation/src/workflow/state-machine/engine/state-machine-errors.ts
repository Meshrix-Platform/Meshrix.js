export class StateMachineError extends Error {
  code: any;
  details: any;
  errorCode: any;
  name: any;
  constructor(errorCode?: any, message?: any, details: Record<string, any> = {}) {
    super(message);
    this.name = 'StateMachineError';
    this.code = errorCode;
    this.errorCode = errorCode;
    this.details = { ok: false, ...details };
  }
}
