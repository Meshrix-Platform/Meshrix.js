export function listConsoleDomainOperationExecutors() {
  return CONSOLE_DOMAIN_OPERATION_EXECUTOR_REGISTRY.map((entry) => ({
    featureId: entry.featureId,
    handlerName: entry.handler.name
  }));
}

export async function executeConsoleDomainOperation({ operationId, input = {}, context = {} } = {}) {
  for (const executor of CONSOLE_DOMAIN_OPERATION_EXECUTOR_REGISTRY) {
    const operationResult = await executor.handler({ operationId, input, context });
    if (operationResult) {
      return operationResult;
    }
  }
  return result(501, {
    ok: false,
    error: {
      code: "console_domain_operation_not_registered",
      message: "Console domain operation is not registered in the specialized executor.",
      details: { operationId: operationId || "" }
    }
  });
}
