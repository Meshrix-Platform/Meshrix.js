#!/usr/bin/env node
/**
 * Sync canonical design assets from `assets/` to the consumer locations that
 * must hold a physical copy. `assets/` is the single source of truth; a
 * consumer either references a canonical file directly or receives a
 * byte-identical projection produced here — never a hand-edited duplicate.
 *
 * Usage:
 *   node tools/generators/sync-design-assets.ts
 *   node tools/generators/sync-design-assets.ts --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname: any = path.dirname(fileURLToPath(import.meta.url));
const ROOT: any = path.resolve(__dirname, "../..");

/**
 * Canonical → consumer projection pairs. Keep this list the only place a
 * design asset is allowed to exist in two locations; derived artifacts that a
 * build step rasterizes or composes (for example the entry-native icon tile)
 * are generated by their owning build and are not listed here.
 */
export const DESIGN_ASSET_PROJECTIONS: ReadonlyArray<{
  source: string;
  target: string;
  purpose: string;
}> = Object.freeze([
  Object.freeze({
    source: "assets/brand/logo.svg",
    target: "apps/console/favicon.svg",
    purpose: "Console favicon served from the application root; identical art to the canonical mark."
  })
]);

function toPosix(filePath?: any): any {
  return path.relative(ROOT, filePath).split(path.sep).join("/");
}

export function syncDesignAssets(check?: any): any {
  const drifts: string[] = [];
  for (const projection of DESIGN_ASSET_PROJECTIONS) {
    const sourcePath: any = path.resolve(ROOT, projection.source);
    const targetPath: any = path.resolve(ROOT, projection.target);
    if (!fs.existsSync(sourcePath)) {
      drifts.push(`missing canonical source ${projection.source}`);
      continue;
    }
    const source: any = fs.readFileSync(sourcePath);
    const current: any = fs.existsSync(targetPath) ? fs.readFileSync(targetPath) : null;
    if (current !== null && current.equals(source)) {
      continue;
    }
    if (check) {
      drifts.push(
        current === null
          ? `missing projection ${projection.target} (from ${projection.source})`
          : `drifted projection ${projection.target} (from ${projection.source})`
      );
      continue;
    }
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, source);
    console.log(`synced ${projection.source} -> ${toPosix(targetPath)}`);
  }
  return drifts;
}

function main(): any {
  const check: any = process.argv.includes("--check");
  const drifts: any = syncDesignAssets(check);
  if (drifts.length === 0) {
    console.log(
      check
        ? "design asset projections are in sync"
        : "design asset projections already in sync"
    );
    return;
  }
  for (const drift of drifts) {
    console.error(`design-assets drift: ${drift}`);
  }
  if (check) {
    console.error("run `node tools/generators/sync-design-assets.ts` to resync");
    process.exitCode = 1;
  }
}

const invokedPath: any = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  main();
}
